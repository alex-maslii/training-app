#!/usr/bin/env node
// Regenerate apps/mobile/src/lib/database.types.ts from the linked Supabase project.
//   --local  generate from the local database (supabase db start) instead
//   --check  fail if the committed file is out of date instead of writing it
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const output = fileURLToPath(new URL('../apps/mobile/src/lib/database.types.ts', import.meta.url));
const generated = execFileSync(
  'npx',
  [
    '--yes',
    'supabase@2.120.0',
    'gen',
    'types',
    'typescript',
    args.includes('--local') ? '--local' : '--linked',
    '--schema',
    'public',
  ],
  { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] },
);

const content =
  `// Generated by \`npm run db:types\`. Do not edit by hand.\n\n${generated}\n` +
  `export type Profile = Tables<'profiles'>\n` +
  `export type Food = Tables<'foods'>\n` +
  `export type LogEntry = Tables<'log_entries'>\n`;

if (args.includes('--check')) {
  // The PostgREST version differs between local and hosted projects; ignore it.
  const normalize = (text) => text.replace(/PostgrestVersion: "[^"]*"/, 'PostgrestVersion: ""');
  if (normalize(readFileSync(output, 'utf8')) !== normalize(content)) {
    console.error(`${output} is out of date. Run \`npm run db:types\` and commit the result.`);
    process.exit(1);
  }
  console.log('Database types are up to date.');
} else {
  writeFileSync(output, content);
  console.log(`Wrote ${output}`);
}
